"""Create minimal stand-ins for Natalio's and Chris's tables.

.. warning::

   **This is not part of my migrations and must never run against the real
   integration database.** Section 3 of team-integration-v1.0.0 says each
   owner creates their own tables, and that nobody creates placeholders for
   another owner's production tables.

   It exists for one reason: my foreign keys point at ``users(id)`` and
   ``assets(id)``, so without those tables I cannot apply a single migration
   or run a single test while developing alone. When Natalio's and Chris's
   real migrations are available, drop the development database, create a
   fresh one, and apply the three owners' migrations in order instead.

The stand-ins deliberately contain only the columns my services reference,
so if I ever accidentally depend on a column that is really theirs, it fails
here rather than silently working.

Run it with::

    python devtools/bootstrap_dev_dependencies.py

:author: Karim Hajj Ali
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import db  # noqa: E402

#: Only the columns my services actually read. Natalio's and Chris's real
#: tables have many more.
STANDIN_SQL = """
CREATE TABLE IF NOT EXISTS users (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       TEXT    NOT NULL UNIQUE,
    full_name      TEXT    NOT NULL,
    role           TEXT    NOT NULL,
    account_status TEXT    NOT NULL DEFAULT 'active',
    deleted        BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS assets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT   NOT NULL,
    asset_type  TEXT   NOT NULL,
    criticality TEXT   NOT NULL,
    status      TEXT   NOT NULL DEFAULT 'active',
    owner_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT
);
"""

#: Canonical role strings from section 4.2.
DEV_USERS = [
    ("karim.admin", "Karim Hajj Ali", "security_administrator"),
    ("rana.analyst", "Rana Khoury", "security_analyst"),
    ("omar.analyst", "Omar Saleh", "security_analyst"),
    ("lina.employee", "Lina Haddad", "regular_employee"),
    ("samir.auditor", "Samir Fares", "auditor"),
]

DEV_ASSETS = [
    ("Primary Domain Controller", "server", "critical", 1),
    ("Finance File Server", "server", "high", 4),
    ("HR Workstation 14", "workstation", "medium", 4),
    ("Customer Records Database", "database", "critical", 1),
    ("Branch Office Router", "network_device", "high", 2),
    ("Payroll Web Application", "application", "high", 4),
]


def guard():
    """Refuse to run unless the caller has opted in explicitly.

    :raises SystemExit: If the opt-in environment variable is absent.
    :return: ``None``
    :rtype: NoneType
    """
    if os.environ.get("KARIM_ALLOW_DEV_BOOTSTRAP") != "yes":
        print(__doc__)
        print("Refusing to run. This creates tables owned by teammates.")
        print("If this really is a throwaway development database, set:")
        print("    KARIM_ALLOW_DEV_BOOTSTRAP=yes")
        raise SystemExit(2)


def main():
    """Create the stand-in tables and seed a few rows.

    :return: Process exit code.
    :rtype: int
    """
    guard()

    with db.transaction() as cur:
        cur.execute(STANDIN_SQL)

    with db.transaction() as cur:
        cur.execute("SELECT count(*) AS n FROM users")
        if cur.fetchone()["n"] == 0:
            for username, full_name, role in DEV_USERS:
                cur.execute(
                    "INSERT INTO users (username, full_name, role) "
                    "VALUES (%s, %s, %s)", (username, full_name, role))
            print("inserted %d stand-in users" % len(DEV_USERS))
        else:
            print("users already populated, left alone")

        cur.execute("SELECT count(*) AS n FROM assets")
        if cur.fetchone()["n"] == 0:
            for name, asset_type, criticality, owner_id in DEV_ASSETS:
                cur.execute(
                    "INSERT INTO assets (name, asset_type, criticality, "
                    "owner_id) VALUES (%s, %s, %s, %s)",
                    (name, asset_type, criticality, owner_id))
            print("inserted %d stand-in assets" % len(DEV_ASSETS))
        else:
            print("assets already populated, left alone")

    print("\nStand-ins ready. These are NOT Natalio's or Chris's real tables.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
