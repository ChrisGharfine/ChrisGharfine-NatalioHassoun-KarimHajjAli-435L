-- Incidents and their investigation notes.
--
-- users(id) and assets(id) are NOT created here. They belong to Natalio and
-- Chris, and section 3 of team-integration-v1.0.0 requires their migrations
-- to run before this one.

CREATE TABLE IF NOT EXISTS incidents (
    incident_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               TEXT        NOT NULL,
    description         TEXT        NOT NULL,
    category            TEXT        NOT NULL,
    severity            TEXT        NOT NULL,
    reporter_id         INTEGER     NOT NULL REFERENCES users(id),
    asset_id            BIGINT          NULL REFERENCES assets(id) ON DELETE RESTRICT,
    assigned_analyst_id INTEGER         NULL REFERENCES users(id),
    status              TEXT        NOT NULL DEFAULT 'Open',
    creation_date       TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolution_date     TIMESTAMPTZ     NULL
);

CREATE TABLE IF NOT EXISTS investigation_notes (
    note_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id        BIGINT      NOT NULL REFERENCES incidents(incident_id) ON DELETE CASCADE,
    analyst_id         INTEGER     NOT NULL REFERENCES users(id),
    note_content       TEXT        NOT NULL,
    creation_timestamp TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_incidents_status  ON incidents(status);
CREATE INDEX IF NOT EXISTS idx_incidents_analyst ON incidents(assigned_analyst_id);
CREATE INDEX IF NOT EXISTS idx_incidents_asset   ON incidents(asset_id);
CREATE INDEX IF NOT EXISTS idx_notes_incident    ON investigation_notes(incident_id);
