-- Vulnerabilities discovered on Chris's assets.
--
-- Section 3: the asset reference is mandatory and uses ON DELETE RESTRICT,
-- so an asset carrying a vulnerability cannot be deleted out from under it.

CREATE TABLE IF NOT EXISTS vulnerabilities (
    vulnerability_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            TEXT        NOT NULL,
    description      TEXT        NOT NULL,
    cve_identifier   TEXT            NULL,
    cvss_score       NUMERIC(3,1)    NULL
        CONSTRAINT vulnerabilities_cvss_range
        CHECK (cvss_score IS NULL OR (cvss_score >= 0.0 AND cvss_score <= 10.0)),
    severity_level   TEXT        NOT NULL,
    asset_id         BIGINT      NOT NULL REFERENCES assets(id) ON DELETE RESTRICT,
    discovery_source TEXT            NULL,
    status           TEXT        NOT NULL DEFAULT 'Open',
    creation_date    TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolution_date  TIMESTAMPTZ     NULL
);

CREATE INDEX IF NOT EXISTS idx_vuln_asset    ON vulnerabilities(asset_id);
CREATE INDEX IF NOT EXISTS idx_vuln_status   ON vulnerabilities(status);
CREATE INDEX IF NOT EXISTS idx_vuln_severity ON vulnerabilities(severity_level);
CREATE INDEX IF NOT EXISTS idx_vuln_cve      ON vulnerabilities(cve_identifier);
