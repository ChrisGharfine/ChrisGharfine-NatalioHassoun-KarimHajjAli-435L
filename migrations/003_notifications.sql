-- Notifications delivered to Natalio's users.

CREATE TABLE IF NOT EXISTS notifications (
    notification_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           INTEGER     NOT NULL REFERENCES users(id),
    title             TEXT        NOT NULL,
    message           TEXT        NOT NULL,
    notification_type TEXT        NOT NULL,
    severity_level    TEXT        NOT NULL,
    status            TEXT        NOT NULL DEFAULT 'Unread',
    creation_date     TIMESTAMPTZ NOT NULL DEFAULT now(),
    read_date         TIMESTAMPTZ     NULL
);

CREATE INDEX IF NOT EXISTS idx_notif_user   ON notifications(user_id);
CREATE INDEX IF NOT EXISTS idx_notif_status ON notifications(status);
CREATE INDEX IF NOT EXISTS idx_notif_type   ON notifications(notification_type);
